DROP TABLE TIPO_EMERGENCIA;

CREATE TABLE TIPO_EMERGENCIA (
    ID_TEM NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    NOMBRE_TEM VARCHAR2(100 BYTE),
    ACTIVO_TEM CHAR(1 BYTE),
    ORDEN_TEM NUMBER(10),
    FECHA_CREACION_TEM DATE DEFAULT SYSDATE,

    CONSTRAINT PK_TIPO_EMERGENCIA PRIMARY KEY (ID_TEM),
    CONSTRAINT NOT_NULL_NOMBRE_TEM CHECK (NOMBRE_TEM IS NOT NULL),
    CONSTRAINT NOT_NULL_ACTIVO_TEM CHECK (ACTIVO_TEM IS NOT NULL),
    CONSTRAINT NOT_NULL_ORDEN_TEM CHECK (ORDEN_TEM IS NOT NULL),
    CONSTRAINT NOT_NULL_FECHA_CREACION_TEM CHECK (FECHA_CREACION_TEM IS NOT NULL),

    CONSTRAINT UNQ_NOMBRE_TEM UNIQUE (NOMBRE_TEM),
    CONSTRAINT UNQ_ORDEN_TEM UNIQUE (ORDEN_TEM),
    CONSTRAINT DEFAULT_ACTIVO_TEM CHECK (ACTIVO_TEM IN ('S', 'N'))
);

